// Converts the data files of the original Mega Empires Calculator
// (https://calculator.mega-empires.com/, by Matt Crawford, CC BY-NC-SA 4.0)
// into typed TypeScript modules under src/data/.
//
// Usage: node scripts/import-calculator-data.mjs <dir-with-original-js-files>
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const src = path.resolve(process.argv[2] ?? '');
const out = path.resolve(import.meta.dirname, '../src/data');
const load = async (f) => Object.values(await import(pathToFileURL(path.join(src, f + '.js')).href))[0];

const header = `// Generated by scripts/import-calculator-data.mjs from the Mega Empires Calculator
// by Matt Crawford (https://crawdad.neocities.org/MCA2/about.html), licensed
// CC BY-NC-SA 4.0. Do not edit by hand; re-run the script instead.\n`;

const clean = (v) => (typeof v === 'string' ? v.replace(/ /g, ' ').trim() : v);

function advance(a) {
  const o = {};
  for (const k of ['name', 'price', 'color', 'description', 'shortDescription', 'credits', 'nextname',
    'bonus', 'trade', 'special', 'extraCredit', 'activate', 'warningTFA']) {
    if (a[k] !== undefined) o[k] = clean(a[k]);
  }
  return o;
}

function calamity(c) {
  const o = {
    name: c.name,
    category: c.category,
    stack: c.stack,
    description: clean(c.description),
    secondaryVictims: clean(c.secondaries) === 'S',
    beneficiary: clean(c.beneficiary) === 'T' ? 'trader' : clean(c.beneficiary) === 'C' ? 'mostCitiesInStock' : null,
  };
  if (c.description34) {
    o.description = clean(c.description5plus);
    o.descriptionFewPlayers = clean(c.description34);
  }
  return o;
}

async function interactions() {
  const text = await readFile(path.join(src, 'interactions.js'), 'utf8');
  const start = text.indexOf('const interactions = [');
  const end = text.indexOf('];', start);
  const literal = text.slice(start + 'const interactions = '.length, end + 1);
  // Parse the object literal: quote keys, then JSON.parse (no code execution).
  const json = literal
    .replace(/([{,]\s*)(advance|block|calamity|direction|effect):/g, '$1"$2":')
    .replace(/,\s*}/g, '}')
    .replace(/,\s*]/g, ']');
  return JSON.parse(json).map((i) => ({ ...i, effect: i.effect.replace(/\s+/g, ' ').trim() }));
}

const files = {
  'advances-we.ts': ['AdvanceDef', 'advancesWestEast', (await load('advances-we')).map(advance)],
  'advances-fe.ts': ['AdvanceDef', 'advancesFarEast', (await load('advances-fe')).map(advance)],
  'calamities-we.ts': ['CalamityDef', 'calamitiesWestEast', (await load('calamities-we')).map(calamity)],
  'calamities-fe.ts': ['CalamityDef', 'calamitiesFarEast', (await load('calamities-fe')).map(calamity)],
  'interactions.ts': ['InteractionDef', 'interactions', await interactions()],
};

for (const [file, [type, name, data]] of Object.entries(files)) {
  const body = `${header}import type { ${type} } from './types';\n\nexport const ${name}: ${type}[] = ${JSON.stringify(data, null, 2)};\n`;
  await writeFile(path.join(out, file), body);
  console.log(file, data.length);
}
